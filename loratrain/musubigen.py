"""Turn a musubi-tuner preset into its two halves: a dataset TOML and argv.

musubi has no single config file. The dataset has its own format (``image_directory``
and ``cache_directory`` per subset, rather than sd-scripts' ``image_dir`` plus a
shared cache), and every training option arrives as a flag instead of a TOML key.
So this module renders the dataset config and the argument list separately, and
reuses ``tomlgen``'s value formatting so both engines write TOML the same way.
"""

from __future__ import annotations

from pathlib import Path

from .presets import Preset
from .tomlgen import _fmt, _sample_prompts

# What a model path is called on the command line, unless the preset says otherwise.
DEFAULT_MODEL_FLAGS = {"dit": "dit", "vae": "vae", "text_encoder": "text_encoder"}


def _value(value) -> str:
    """Format one TOML value, including the arrays musubi wants for resolution."""
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_fmt(item) for item in value) + "]"
    return _fmt(value)


def render_dataset(general: dict, datasets: list[dict]) -> str:
    """Render musubi's dataset config: one ``[general]``, then ``[[datasets]]``."""
    lines: list[str] = ["# generated by loratrain for musubi-tuner - edit freely", ""]

    lines.append("[general]")
    for key, value in general.items():
        lines.append(f"{key} = {_value(value)}")
    lines.append("")

    for dataset in datasets:
        lines.append("[[datasets]]")
        for key, value in dataset.items():
            lines.append(f"{key} = {_value(value)}")
        lines.append("")

    return "\n".join(lines)


def build_dataset(
    preset: Preset,
    *,
    dataset_dir: Path | str,
    out_dir: Path | str,
    repeats: int | None = None,
    resolution: int | None = None,
    caption_ext: str = ".txt",
) -> tuple[dict, list[dict]]:
    """The two sections of musubi's dataset config for one image folder.

    ``cache_directory`` is set explicitly: musubi otherwise caches next to the
    images, and two datasets that share a cache silently train on each other's
    latents.
    """
    resolution = resolution or preset.resolution
    repeats = repeats if repeats is not None else preset.default_repeats

    general = {
        "resolution": [resolution, resolution],
        "caption_extension": caption_ext,
        "batch_size": 1,
        "enable_bucket": True,
        "bucket_no_upscale": True,
        "min_bucket_reso": preset.min_bucket_reso,
        "max_bucket_reso": preset.max_bucket_reso,
        "bucket_reso_steps": 64,
    }

    datasets = [
        {
            "image_directory": str(Path(dataset_dir)),
            "cache_directory": str(Path(out_dir) / "cache"),
            "num_repeats": repeats,
        }
    ]

    return general, datasets


def build_flags(
    preset: Preset,
    *,
    out_dir: Path | str,
    name: str,
    models: dict[str, str | None],
    units: int | None = None,
    trigger: str | None = None,
    seed: int = 42,
    dim: int | None = None,
    alpha: int | None = None,
    lr: float | None = None,
    dataset_config: Path | str | None = None,
    sample_prompts: Path | str | None = None,
    overrides: dict | None = None,
) -> dict:
    """Everything the script takes as a flag, as ``{flag_name: value}``.

    Booleans mean "switch on" (``True`` becomes a bare ``--flag``); ``None`` means
    "leave it out". Keeping it a dict is what lets the caller drop the flags this
    musubi version does not know, exactly like ``tomlgen``'s keys are dropped.
    """
    units = units if units is not None else preset.units
    out_path = Path(out_dir)

    flags: dict[str, object] = {}

    for key in ("dit", "vae", "text_encoder"):
        value = models.get(key)
        if value:
            flags[preset.model_flags.get(key, DEFAULT_MODEL_FLAGS[key])] = value

    if dataset_config is not None:
        flags["dataset_config"] = str(dataset_config)

    flags["mixed_precision"] = "bf16"
    flags["sdpa"] = True
    flags["gradient_checkpointing"] = True
    flags["max_data_loader_n_workers"] = 2
    flags["persistent_data_loader_workers"] = True

    flags["network_module"] = preset.network_module
    flags["network_dim"] = dim or preset.network_dim
    flags["network_alpha"] = alpha if alpha is not None else preset.network_alpha

    flags["optimizer_type"] = "adamw8bit"
    flags["learning_rate"] = lr if lr is not None else preset.lr
    flags["lr_scheduler"] = preset.lr_scheduler
    flags["lr_warmup_steps"] = preset.lr_warmup_steps

    for key, value in preset.extra.items():
        flags.setdefault(key, value)

    flags["output_dir"] = str(out_path)
    flags["output_name"] = name
    flags["logging_dir"] = str(out_path / "logs")
    flags["seed"] = seed
    flags["save_every_n_epochs" if preset.unit_kind == "epochs" else "save_every_n_steps"] = preset.save_every
    flags["max_train_epochs" if preset.unit_kind == "epochs" else "max_train_steps"] = units

    if sample_prompts is not None:
        flags["sample_prompts"] = str(sample_prompts)
        flags["sample_every_n_epochs"] = 1

    if overrides:
        flags.update(overrides)

    return flags


def flags_to_args(flags: dict) -> list[str]:
    """Render the flag dict as argv, in the order it was built."""
    args: list[str] = []
    for key, value in flags.items():
        if value is None:
            continue
        if value is True:
            args.append(f"--{key}")
        elif value is False:
            continue
        else:
            args.extend([f"--{key}", str(value)])
    return args


def write_files(
    preset: Preset,
    general: dict,
    datasets: list[dict],
    *,
    out_dir: Path | str,
    trigger: str | None = None,
) -> tuple[Path, Path | None]:
    """Write ``musubi_dataset.toml`` and, when sampling is on, the prompt file."""
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    config_path = out_path / "musubi_dataset.toml"
    config_path.write_text(render_dataset(general, datasets), encoding="utf-8")

    sample_path = None
    if preset.sampling and trigger:
        sample_path = out_path / "sample_prompts.txt"
        sample_path.write_text(_sample_prompts(trigger), encoding="utf-8")

    return config_path, sample_path
