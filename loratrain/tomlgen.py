"""Turn a preset plus a dataset into a kohya sd-scripts TOML config.

Everything is built as ordered dicts first and rendered last, so the config can be
filtered against the flags the installed sd-scripts actually accepts before it is
written. The section order is fixed because TOML tables extend whatever precedes
them: top-level keys, then ``[general]``, then ``[[datasets]]``, then
``[[datasets.subsets]]``.
"""

from __future__ import annotations

from pathlib import Path

from .presets import Preset


class TomlError(ValueError):
    """Raised when a value cannot be written as TOML."""


def _fmt(value) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        text = repr(value)
        if "." not in text and "e" not in text and "E" not in text:
            text += ".0"
        return text
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    raise TomlError(f"cannot serialise {type(value).__name__}")


def render(top: dict, general: dict, dataset: dict, subsets: list[dict]) -> str:
    """Render the four parts into TOML text."""
    lines: list[str] = ["# generated by loratrain - edit freely", ""]

    for key, value in top.items():
        lines.append(f"{key} = {_fmt(value)}")

    lines.append("")

    if general:
        lines.append("[general]")
        for key, value in general.items():
            lines.append(f"{key} = {_fmt(value)}")
        lines.append("")

    lines.append("[[datasets]]")
    for key, value in dataset.items():
        lines.append(f"{key} = {_fmt(value)}")
    lines.append("")

    for subset in subsets:
        lines.append("[[datasets.subsets]]")
        for key, value in subset.items():
            lines.append(f"{key} = {_fmt(value)}")
        lines.append("")

    return "\n".join(lines)


def build_parts(
    preset: Preset,
    *,
    dataset_dir: Path | str,
    out_dir: Path | str,
    name: str,
    models: dict[str, str | None],
    repeats: int | None = None,
    trigger: str | None = None,
    resolution: int | None = None,
    min_bucket: int | None = None,
    max_bucket: int | None = None,
    dim: int | None = None,
    alpha: int | None = None,
    lr: float | None = None,
    units: int | None = None,
    seed: int = 42,
    caption_ext: str = ".txt",
    overrides: dict | None = None,
) -> tuple[dict, dict, dict, list[dict]]:
    """Build the four sections of a config without writing anything."""
    resolution = resolution or preset.resolution
    min_bucket = min_bucket or preset.min_bucket_reso
    max_bucket = max_bucket or preset.max_bucket_reso
    repeats = repeats if repeats is not None else preset.default_repeats
    units = units if units is not None else preset.units
    out_path = Path(out_dir)

    top: dict = {}

    top["pretrained_model_name_or_path"] = models["base"]
    model_keys = [key for key in preset.requires if key != "base"]
    if preset.supports_vae:
        model_keys.append("vae")
    for key in model_keys:
        value = models.get(key)
        if value:
            top[key] = value

    top["output_dir"] = str(out_path)
    top["output_name"] = name
    top["save_model_as"] = "safetensors"
    top["save_precision"] = "bf16"
    if preset.unit_kind == "epochs":
        top["save_every_n_epochs"] = preset.save_every
        top["max_train_epochs"] = units
    else:
        top["save_every_n_steps"] = preset.save_every
        top["max_train_steps"] = units

    top["mixed_precision"] = "bf16"
    top["gradient_checkpointing"] = True
    top["train_batch_size"] = 1
    top["max_data_loader_n_workers"] = 2
    top["seed"] = seed

    top["network_module"] = preset.network_module
    top["network_dim"] = dim or preset.network_dim
    top["network_alpha"] = alpha if alpha is not None else preset.network_alpha

    top["optimizer_type"] = "AdamW8bit"
    top["learning_rate"] = lr if lr is not None else preset.lr
    if preset.text_encoder_lr is not None:
        top["unet_lr"] = lr if lr is not None else preset.lr
        top["text_encoder_lr"] = preset.text_encoder_lr
    top["lr_scheduler"] = preset.lr_scheduler
    top["lr_warmup_steps"] = preset.lr_warmup_steps
    top["max_grad_norm"] = preset.max_grad_norm

    for key, value in preset.extra.items():
        top.setdefault(key, value)

    top["logging_dir"] = str(out_path / "logs")
    top["log_with"] = "tensorboard"

    if preset.sampling and trigger:
        top["sample_every_n_epochs"] = 1
        top["sample_sampler"] = "euler_a"
        top["sample_prompts"] = str(out_path / "sample_prompts.txt")

    if overrides:
        top.update(overrides)

    general = {
        "caption_extension": caption_ext,
        "keep_tokens": 1,
        "shuffle_caption": False,
        "caption_dropout_rate": 0.05,
    }

    dataset = {
        "resolution": resolution,
        "batch_size": 1,
        "enable_bucket": True,
        "min_bucket_reso": min_bucket,
        "max_bucket_reso": max_bucket,
        "bucket_reso_steps": 64,
        "bucket_no_upscale": True,
    }

    subsets = [{"image_dir": str(dataset_dir), "num_repeats": repeats}]

    return top, general, dataset, subsets


def _sample_prompts(trigger: str) -> str:
    rows = [
        (f"{trigger}, close-up portrait, looking at the camera, neutral expression, soft window light", 1024, 1024),
        (f"{trigger}, head and shoulders, three quarter view, indoor light", 1024, 1024),
        (f"{trigger}, full body shot, standing, plain background, daylight", 832, 1216),
    ]
    lines: list[str] = []
    for index, (prompt, width, height) in enumerate(rows, start=1):
        lines.append(prompt)
        lines.append(f"--n sample{index}")
        lines.append(f"--w {width}")
        lines.append(f"--h {height}")
        lines.append("--d 42")
        lines.append("--s 30")
        lines.append("--l 6.0")
        lines.append("")
    return "\n".join(lines)


def write_files(
    preset: Preset,
    top: dict,
    general: dict,
    dataset: dict,
    subsets: list[dict],
    *,
    out_dir: Path | str,
    trigger: str | None = None,
) -> tuple[Path, Path | None]:
    """Write ``train.toml`` and, when sampling is on, the prompt file."""
    out_path = Path(out_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    config_path = out_path / "train.toml"
    config_path.write_text(render(top, general, dataset, subsets), encoding="utf-8")

    sample_path = None
    if preset.sampling and trigger:
        sample_path = out_path / "sample_prompts.txt"
        sample_path.write_text(_sample_prompts(trigger), encoding="utf-8")

    return config_path, sample_path
